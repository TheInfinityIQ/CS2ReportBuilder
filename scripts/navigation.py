"""Build compact folder maps and a local searchable catalog without using a model.

Generated maps are discovery aids, never evidence or project authority. Repository
maps are checked in CI; data maps and their catalog stay on the local device.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import sys
import xml.etree.ElementTree as ET
import zipfile
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote

REPO = Path(__file__).resolve().parents[1]
MARKER = "<!-- generated by scripts/navigation.py; do not edit -->"
INDEX = "00_INDEX.md"
SKIP = {".git", ".venv", "node_modules", "__pycache__", ".pytest_cache", ".ruff_cache",
        ".navigation", ".agents", ".codex", ".aws", ".idea"}
TEXT = {".md", ".txt", ".py", ".ps1", ".js", ".json", ".jsonl", ".yml", ".yaml", ".toml", ".csv", ".tsv"}
DOC = {".md", ".txt", ".docx", ".pdf"}
LIMIT = 48


def natural(value):
    return tuple((0, int(p)) if p.isdigit() else (1, p.casefold()) for p in re.split(r"(\d+)", value))


def shorten(text, size=210):
    text = re.sub(r"\s+", " ", text).strip().replace("|", "/")
    return text if len(text) <= size else text[:size - 1].rsplit(" ", 1)[0] + "…"


def metadata():
    return json.loads((REPO / "navigation/metadata.json").read_text(encoding="utf-8"))


def is_generated(path):
    return path.name == INDEX and path.is_file() and path.read_text(encoding="utf-8").startswith(MARKER)


def excluded(name):
    lower = name.casefold()
    return (name in SKIP or "browser_profile" in lower
            or "firefox_profile" in lower or lower.startswith(".env") or lower in {"credentials", "secrets"}
            or lower.endswith((".egg-info", ".pyc", ".log", ".sqlite-wal", ".sqlite-shm", ".pem", ".key")))


def walk(root):
    files, folders = [], []
    for parent, dirs, names in os.walk(root, followlinks=False):
        base = Path(parent)
        dirs[:] = sorted((d for d in dirs if not excluded(d) and not (base / d).is_symlink()), key=natural)
        folders.append(base)
        for name in sorted(names, key=natural):
            path = base / name
            if excluded(name) or path.is_symlink() or is_generated(path):
                continue
            files.append(path)
    return files, folders


def docx_text(path):
    with zipfile.ZipFile(path) as archive:
        entry = archive.getinfo("word/document.xml")
        if entry.file_size > 16_000_000:
            raise ValueError("document XML exceeds extraction limit")
        tree = ET.fromstring(archive.read(entry))
    ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
    return "\n".join("".join(p.itertext()) for p in tree.findall(".//w:p", ns))


def status_for(rel, profile, meta):
    for prefix, status in meta[profile]["statuses"]:
        if rel.startswith(prefix):
            return status
    return "source" if profile == "repo" else "local artifact"


def describe(path, root, profile, meta, previous=None):
    rel = path.relative_to(root).as_posix()
    size = path.stat().st_size
    # Reuse unchanged local records on warm runs. Repo scans always hash content.
    stamp = [size, path.stat().st_mtime_ns]
    if previous and previous.get("stamp") == stamp:
        return previous
    ext = path.suffix.casefold()
    record = {"path": rel, "bytes": size, "status": status_for(rel, profile, meta),
              "summary": f"{path.stem.replace('_', ' ')} ({ext.lstrip('.') or 'file'}).",
              "basis": "filename", "date": None, "date_basis": None, "sha256": None}
    text = ""
    if ext in TEXT and size <= 16_000_000 and not (profile == "data" and ext == ".csv" and size > 250_000):
        raw = path.read_bytes().replace(b"\r\n", b"\n")
        record["sha256"] = hashlib.sha256(raw).hexdigest()
        record["bytes"] = len(raw)  # stable across Windows/Linux git checkouts
        text = raw.decode("utf-8-sig", errors="replace")
    elif ext == ".docx":
        with path.open("rb") as stream:
            record["sha256"] = hashlib.file_digest(stream, "sha256").hexdigest()
        try:
            text = docx_text(path)
        except (ValueError, zipfile.BadZipFile, KeyError, ET.ParseError):
            record["basis"] = "filename; document extraction failed"
    if text:
        record["basis"] = "extracted"
        if ext == ".py":
            try:
                tree = ast.parse(text)
                doc = ast.get_docstring(tree)
                names = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))]
                record["summary"] = shorten(doc or ("Python definitions: " + ", ".join(names[:8]) if names else text.splitlines()[0]))
            except SyntaxError:
                record["summary"] = "Python source; syntax not parsed by this runtime."
        elif ext == ".json":
            try:
                obj = json.loads(text)
                if isinstance(obj, dict):
                    record["summary"] = shorten(obj.get("decision") or obj.get("description") or "JSON fields: " + ", ".join(list(obj)[:10]))
                else:
                    record["summary"] = f"JSON collection ({len(obj) if isinstance(obj, list) else type(obj).__name__})."
            except (ValueError, TypeError):
                record["summary"] = "JSON-labelled text; strict JSON parse failed."
        else:
            lines = [line.strip().strip("# ") for line in text.splitlines() if line.strip()]
            record["summary"] = shorten(" — ".join(lines[:2]))
        record["headings"] = [shorten(m.group(1), 90) for m in re.finditer(r"^#{1,3}\s+(.+)$", text, re.MULTILINE)][:10]
    match = re.search(r"(?<!\d)(20\d{2}-\d{2}-\d{2})(?!\d)", path.name)
    if match:
        record["date"], record["date_basis"] = match.group(1), "filename"
    elif text:
        labelled = text[:5000].replace("*", "")
        match = re.search(r"(?:Prepared|Date|generated|Snapshot date)\s*[:\n]?\s*(20\d{2}-\d{2}-\d{2})", labelled, re.IGNORECASE)
        if match:
            record["date"], record["date_basis"] = match.group(1), "document label"
        else:
            match = re.search(r"(?:Prepared|Date|Snapshot date)\s*[:\n]?\s*(\d{1,2}\s+[A-Za-z]+\s+20\d{2})", labelled, re.IGNORECASE)
            if match:
                for fmt in ("%d %B %Y", "%d %b %Y"):
                    try:
                        record["date"] = datetime.strptime(match.group(1), fmt).replace(tzinfo=UTC).date().isoformat()
                        record["date_basis"] = "document label"
                        break
                    except ValueError:
                        continue
    override = meta[profile].get("files", {}).get(rel, {})
    for key in ("summary", "status", "date", "supersedes", "read_when"):
        if key in override:
            record[key] = override[key]
    if "summary" in override:
        record["basis"] = "curated"
        reviewed = override.get("reviewed_sha256")
        record["summary_review"] = "current" if reviewed == record["sha256"] else "needs review"
    if "date" in override:
        record["date_basis"] = "curated; see metadata provenance"
    if profile == "data":
        record["stamp"] = stamp
    return record


def link(label, target):
    return f"[{label.replace('[', '(').replace(']', ')')}]({quote(target, safe='/.-_')})"


def index_folders(root, folders, records, profile):
    if profile == "repo":
        return set(folders)
    result = {root}
    for rec in records:
        rel = rec["path"]
        # Keep fresh-coach inputs byte-for-byte unchanged and do not repeat data schemas.
        if rel.startswith(("01_Demos/", "02_Analysis/", "06_Handoff_and_Tests/packets/")):
            continue
        if Path(rel).suffix.casefold() in DOC | {".py", ".ps1", ".js"}:
            directory = (root / rel).parent
            result.update([directory, *[p for p in directory.parents if p != root.parent and root in p.parents]])
    for folder in folders:
        rel = folder.relative_to(root)
        if len(rel.parts) == 1 or (rel.parts and rel.parts[0] in {"01_Demos", "02_Analysis"} and len(rel.parts) == 2):
            result.add(folder)
        if rel.parts[:2] == ("07_Development", "stage_steps") and len(rel.parts) == 3:
            result.update((folder, folder.parent))
    return result


def render(folder, root, records, indexes, profile, meta):
    rel = folder.relative_to(root).as_posix()
    direct = [r for r in records if (r["path"].rsplit("/", 1)[0] if "/" in r["path"] else ".") == rel]
    subtree = [r for r in records if rel == "." or r["path"].startswith(rel + "/")]
    own = meta[profile].get("folders", {}).get(rel, "Folder map; descriptions are discovery hints, not verified claims.")
    lines = [MARKER, f"# {folder.name} file map", "", own, "",
             "Read only the files relevant to the task. Authority comes from the original documents, not this index.",
             f"Catalog: **{len(subtree):,} files** below this folder. Extracted/filename descriptions are not semantic reviews."]
    if folder != root:
        parent = next((p for p in folder.parents if p in indexes), root)
        lines += ["", link("Parent map", os.path.relpath(parent / INDEX, folder).replace("\\", "/"))]
    children = sorted([p for p in indexes if p != folder and next((q for q in p.parents if q in indexes), root) == folder], key=lambda p: natural(p.name))
    if children:
        lines += ["", "## Subfolders", ""]
        for child in children[:LIMIT]:
            cr = child.relative_to(root).as_posix()
            lines.append(f"- {link(child.name, os.path.relpath(child / INDEX, folder).replace(chr(92), '/'))}: " + meta[profile].get("folders", {}).get(cr, "Open for local file references."))
        if len(children) > LIMIT:
            lines.append(f"- {len(children) - LIMIT} more mapped folders; use the catalog query below.")
    if direct:
        timeline = "history" in rel or "architecture_review" in rel or rel.endswith("ai_chat_history") or rel.startswith("07_Development")
        direct.sort(key=lambda r: (r["date"] is None, r["date"] or "", natural(r["path"])) if timeline else natural(r["path"]))
        lines += ["", "## Files" + (" (documented dates first, oldest to newest)" if timeline else ""), "",
                  "Undated entries use natural filename/version order; filesystem modification times are never historical dates." if timeline else "Summary basis: curated, extracted, or filename. Curated summaries flag edits that need review.", "",
                  "| File | Contents / read when | Status / date | Basis |", "|---|---|---|---|"]
        for rec in direct[:LIMIT]:
            summary = rec["summary"]
            if rec.get("read_when"):
                summary += " Read when: " + rec["read_when"]
            if rec.get("supersedes"):
                summary += " Supersedes: " + rec["supersedes"]
            basis = rec["basis"] + ("; summary needs review" if rec.get("summary_review") == "needs review" else "")
            lines.append(f"| {link(Path(rec['path']).name, Path(rec['path']).name)} | {summary} | {rec['status']} / {rec['date'] or 'undated'} | {basis} |")
        if len(direct) > LIMIT:
            lines += ["", f"**{len(direct) - LIMIT} more files** are individually described in the catalog. Use `--offset 48` for the next page."]
    if not direct and not children:
        lines += ["", "Bulk artifacts are catalogued individually; no data tables are embedded in this map."]
    lines += ["", "## Find a specific file", "", "Run from the Git checkout:", "", "```powershell"]
    scope = "" if profile == "repo" else ' --root "../demoparser" --profile data'
    lines += [f'python scripts/navigation.py find{scope} --under "{rel}" --limit 20', "```", "",
              "Refresh: `python scripts/navigation.py build" + scope + "`. Verify: replace `build` with `check`.", ""]
    return "\n".join(lines)


def load_catalog(root):
    path = root / ".navigation/catalog.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()] if path.exists() else []


def generate(root, profile, meta, force=False):
    files, folders = walk(root)
    cached = {r["path"]: r for r in load_catalog(root)} if profile == "data" and not force else {}
    # A metadata change invalidates warm summaries as well as source changes.
    config_hash = hashlib.sha256(json.dumps(meta[profile], sort_keys=True).encode()).hexdigest()
    signature = root / ".navigation/metadata.sha256"
    if not signature.exists() or signature.read_text().strip() != config_hash:
        cached = {}
    records = [describe(p, root, profile, meta, cached.get(p.relative_to(root).as_posix())) for p in files]
    records.sort(key=lambda r: r["path"])
    indexes = index_folders(root, folders, records, profile)
    outputs = {p / INDEX: render(p, root, records, indexes, profile, meta) for p in indexes}
    outputs[root / ".navigation/catalog.jsonl"] = "".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in records)
    outputs[signature] = config_hash + "\n"
    return outputs, records


def refresh(root, profile, meta, check=False, force=False):
    outputs, records = generate(root, profile, meta, force)
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path.relative_to(root).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                if path.name == INDEX and path.exists() and not is_generated(path):
                    raise ValueError(f"Refusing to overwrite handwritten {path}")
                path.write_text(content, encoding="utf-8", newline="\n")
    # Only remove this tool's obsolete maps, never handwritten files.
    _, folders = walk(root)
    for folder in folders:
        if profile == "data" and folder.relative_to(root).as_posix().startswith("06_Handoff_and_Tests/packets/"):
            continue
        old = folder / INDEX
        if old not in outputs and is_generated(old):
            stale.append(old.relative_to(root).as_posix())
            if not check:
                old.unlink()
    pending = [r["path"] for r in records if r.get("summary_review") == "needs review"]
    print(json.dumps({"files": len(records), "maps": sum(p.name == INDEX for p in outputs),
                      "stale_outputs": len(stale), "summaries_needing_review": pending}, ensure_ascii=False))
    if check:
        for path in stale[:12]:
            print("STALE " + path)
    return 1 if pending or (check and stale) else 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "check", "find", "review"])
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument("--profile", choices=["repo", "data"], default="repo")
    parser.add_argument("--query", default="")
    parser.add_argument("--under", default=".")
    parser.add_argument("--limit", type=int, default=20)
    parser.add_argument("--offset", type=int, default=0)
    parser.add_argument("--force", action="store_true", help="Rehash local documents; bypass warm metadata cache")
    parser.add_argument("--path", help="Relative file to describe after reading it")
    parser.add_argument("--summary", help="Reviewed description; required for review")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if not root.is_dir() or args.limit < 1 or args.offset < 0:
        parser.error("root must exist; limit must be positive; offset must be nonnegative")
    if args.command == "review":
        if not args.path or not args.summary:
            parser.error("review requires --path and --summary after inspecting the source")
        path = (root / args.path).resolve()
        if not path.is_relative_to(root) or not path.is_file():
            parser.error("review path must be a file inside root")
        meta = metadata()
        rec = describe(path, root, args.profile, meta)
        if rec["sha256"] is None:
            parser.error("review bindings are for readable source documents, not bulk binary files")
        entry = meta[args.profile].setdefault("files", {}).setdefault(path.relative_to(root).as_posix(), {})
        entry.update(summary=shorten(args.summary), reviewed_sha256=rec["sha256"])
        (REPO / "navigation/metadata.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        print("Summary bound to inspected source; run build to refresh maps.")
        return 0
    if args.command != "find":
        return refresh(root, args.profile, metadata(), args.command == "check", args.force)
    catalog = load_catalog(root)
    if not catalog:
        parser.error("catalog missing; run build first")
    under = args.under.replace("\\", "/").strip("/")
    terms = args.query.casefold().split()
    selected = [r for r in catalog if (under == "." or r["path"] == under or r["path"].startswith(under + "/"))
                and all(term in json.dumps(r, ensure_ascii=False).casefold() for term in terms)]
    for rec in selected[args.offset:args.offset + args.limit]:
        print(json.dumps(rec, ensure_ascii=False))
    print(json.dumps({"matches": len(selected), "shown": len(selected[args.offset:args.offset + args.limit]),
                      "statuses": dict(Counter(r["status"] for r in selected))}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
